const fs = require('fs');
const path = require('path');
const {compareVersions, isVersionGreaterOrEqual} = require('./utils');

const RELEASE_TAG = /^\d+\.\d+\.\d+$/;

/**
 * Newest release tag of a major. Pre-releases and non-semver tags are skipped:
 * forks carry tags such as release/2.x-as-shipped that compare-versions rejects.
 */
function latestLineTag(tags, major) {
  return tags
    .filter(tag => RELEASE_TAG.test(tag) && tag.split('.')[0] === String(major))
    .sort(compareVersions)
    .pop() || null;
}

function nextPatchVersion(version) {
  const [major, minor, patch] = version.split('.').map(Number);
  return `${major}.${minor}.${patch + 1}`;
}

function renderRefsFile({version, baseline, refs}) {
  const entries = [[`'*'`, baseline], ...Object.keys(refs).sort().map(key => [`'${key}'`, refs[key]])]
    .map(([key, ref]) => `${key}: '${ref}'`)
    .join(', ');
  return [
    `// Generated by bin/make-release-refs.js. Builds ${version} from the ${baseline} line.`,
    `module.exports = {`,
    `  refs: {${entries}},`,
    `  pins: {},`,
    `};`,
    ``,
  ].join('\n');
}

/**
 * Works out the refs file for the next patch release of a major.
 *
 * Every repository is built from the line's last tag, except those whose
 * release/<major>.x carries commits the tag does not. The tag sits on a generated
 * "Release X" commit, so "carries commits" is measured from the tag's parent, the
 * source commit the branch was cut from. Comparing against the tag itself would
 * count that generated commit and misread every untouched branch as patched.
 *
 * git is injected: {listTags(url), hasBranch(url, branch), commitsAhead(url, tag, branch)}.
 */
async function generateReleaseRefs({major, buildConfig, git, historyDir, version}) {
  const magento2 = buildConfig.find(entry => entry.key === 'magento2');
  if (!magento2) throw new Error('build config has no magento2 entry');

  const tags = await git.listTags(magento2.repoUrl);
  const newestMajor = Math.max(...tags.filter(tag => RELEASE_TAG.test(tag)).map(tag => Number(tag.split('.')[0])));
  if (Number(major) >= newestMajor) {
    throw new Error(`${major}.x is the newest released major; build it from the default branch without a refs file`);
  }

  const baseline = latestLineTag(tags, major);
  if (!baseline) throw new Error(`no ${major}.x release tag in ${magento2.repoUrl}`);

  const historyFile = path.join(historyDir, `${baseline}.json`);
  if (!fs.existsSync(historyFile)) {
    throw new Error(`no history file for ${baseline} (${historyFile}); the build reads the baseline's dependencies from it`);
  }

  const release = version || nextPatchVersion(baseline);
  if (tags.includes(release)) throw new Error(`${release} is already tagged`);
  if (release.split('.')[0] !== String(major) || !isVersionGreaterOrEqual(release, nextPatchVersion(baseline))) {
    throw new Error(`${release} does not follow ${baseline}`);
  }

  const branch = `release/${major}.x`;
  const refs = {};
  const notes = [];
  for (const entry of buildConfig) {
    if (!entry.repoUrl || (entry.fromTag && !isVersionGreaterOrEqual(release, entry.fromTag))) continue;
    if (!await git.hasBranch(entry.repoUrl, branch)) continue;
    const ahead = await git.commitsAhead(entry.repoUrl, baseline, branch);
    if (ahead > 0) {
      refs[entry.key] = branch;
      notes.push(`${entry.key}: ${branch} is ${ahead} commit(s) past ${baseline}`);
    } else {
      notes.push(`${entry.key}: ${branch} has nothing past ${baseline}; built from the tag`);
    }
  }
  if (!Object.keys(refs).length) {
    throw new Error(`no ${branch} has commits past ${baseline}; there is nothing to release`);
  }

  return {version: release, baseline, refs, notes, content: renderRefsFile({version: release, baseline, refs})};
}

module.exports = {
  generateReleaseRefs,
  latestLineTag,
  nextPatchVersion,
  renderRefsFile,
};
